export function getPresetById(id) {
  return AVATAR_PRESETS.find(p => p.id === id) || null;
}

export function getPresetsByFilter(gender = 'all', role = 'all') {
  return AVATAR_PRESETS.filter(p => {
    const matchGender = gender === 'all' || p.gender === gender;
    const matchRole = role === 'all' || p.role === role;
    return matchGender && matchRole;
  });
}
