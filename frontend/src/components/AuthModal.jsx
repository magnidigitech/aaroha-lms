import React, { useState, useEffect } from 'react';
import { X, Lock, Mail, ArrowRight, Eye, EyeOff, ShieldAlert, KeyRound, CheckCircle2, ArrowLeft, RefreshCw } from 'lucide-react';
import aarohaLogo from '../assets/aaroha_logo.webp';
import { api } from '../apiService';

export default function AuthModal({ isOpen, onClose, onLogin, onOpenActivation, intendedCourseTitle, initialMode = 'login', initialResetToken = '' }) {
  const [mode, setMode] = useState(initialMode); // 'login' | 'forgot' | 'reset'
  const [loginEmail, setLoginEmail] = useState('');
  const [loginPassword, setLoginPassword] = useState('');
  const [showLoginPassword, setShowLoginPassword] = useState(false);
  const [errorMsg, setErrorMsg] = useState('');
  const [infoMsg, setInfoMsg] = useState('');
  const [loading, setLoading] = useState(false);

  // Forgot password & reset state
  const [forgotEmail, setForgotEmail] = useState('');
  const [resetToken, setResetToken] = useState(initialResetToken);
  const [newPassword, setNewPassword] = useState('');
  const [resetGeneratedLink, setResetGeneratedLink] = useState('');

  useEffect(() => {
    if (isOpen) {
      if (initialMode) setMode(initialMode);
      if (initialResetToken) setResetToken(initialResetToken);
    }
  }, [isOpen, initialMode, initialResetToken]);

  if (!isOpen) return null;

  const handleLoginSubmit = async (e) => {
    e.preventDefault();
    setErrorMsg('');
    setInfoMsg('');
    setLoading(true);

    try {
      const success = await onLogin(loginEmail, loginPassword);
      if (!success) {
        setErrorMsg('Invalid email or password. Please verify your institutional credentials.');
      } else {
        onClose();
      }
    } catch (err) {
      const msg = err.message || '';
      if (msg.includes('pending activation') || msg.includes('single-use invitation')) {
        setErrorMsg('Your account invitation is pending activation. Please use the activation link generated by the administrator to set your password.');
      } else if (msg.includes('deactivated') || msg.includes('revoked')) {
        setErrorMsg('This account has been deactivated by administrator. Access revoked.');
      } else {
        setErrorMsg(msg || 'Invalid email or password. Please verify your credentials.');
      }
    } finally {
      setLoading(false);
    }
  };

  const handleForgotSubmit = async (e) => {
    e.preventDefault();
    setErrorMsg('');
    setInfoMsg('');
    setLoading(true);

    try {
      const res = await api.forgotPassword(forgotEmail);
      if (res && res.success) {
        setInfoMsg(res.message || 'Password reset token generated.');
        if (res.reset_url) {
          setResetGeneratedLink(res.reset_url);
          if (res.reset_token) {
            setResetToken(res.reset_token);
          }
        }
      } else {
        setErrorMsg(res?.error || 'Failed to process password reset.');
      }
    } catch (err) {
      setErrorMsg(err.message || 'Error processing password reset request.');
    } finally {
      setLoading(false);
    }
  };

  const handleResetSubmit = async (e) => {
    e.preventDefault();
    setErrorMsg('');
    setInfoMsg('');

    if (newPassword.length < 8) {
      setErrorMsg('New password must be at least 8 characters long.');
      return;
    }

    setLoading(true);
    try {
      const res = await api.resetPassword({ token: resetToken, password: newPassword });
      if (res && res.success) {
        setInfoMsg('Password updated successfully! Please sign in with your new credentials.');
        setMode('login');
        setLoginEmail(forgotEmail);
        setLoginPassword(newPassword);
        setResetGeneratedLink('');
      } else {
        setErrorMsg(res?.error || 'Failed to reset password.');
      }
    } catch (err) {
      setErrorMsg(err.message || 'Invalid or expired password reset token.');
    } finally {
      setLoading(false);
    }
  };

  const handleAutofill = (email, password) => {
    setLoginEmail(email);
    setLoginPassword(password);
  };

  return (
    <div className="fixed inset-0 z-50 overflow-y-auto bg-slate-950/70 backdrop-blur-xs flex items-center justify-center p-3 sm:p-4">
      <div className="relative bg-white rounded-2xl sm:rounded-3xl max-w-md w-full shadow-2xl border border-slate-200 overflow-hidden my-auto flex flex-col max-h-[92dvh] animate-in fade-in zoom-in-95 duration-150">
        {/* Header */}
        <div className="shrink-0 bg-slate-900 px-5 py-4 sm:px-6 sm:py-5 text-white text-center relative border-b border-slate-800">
          <button
            onClick={onClose}
            className="absolute top-3.5 right-3.5 p-1.5 rounded-full bg-slate-800 hover:bg-slate-700 text-white transition-colors cursor-pointer"
            aria-label="Close modal"
          >
            <X className="w-4 h-4" />
          </button>

          <div className="mb-2 flex justify-center">
            <div className="inline-flex bg-white px-2.5 py-1 rounded-xl border border-slate-200 shadow-xs items-center">
              <img
                src={aarohaLogo}
                alt="Aaroha Technologies"
                className="h-5.5 sm:h-6 w-auto object-contain"
              />
            </div>
          </div>

          <h2 className="text-lg sm:text-xl font-extrabold text-white">
            {mode === 'login' && 'Sign In to Your Workspace'}
            {mode === 'forgot' && 'Account Password Recovery'}
            {mode === 'reset' && 'Set New Account Password'}
          </h2>

          <p className="text-[11px] sm:text-xs text-slate-400 mt-1 line-clamp-2 max-w-xs mx-auto">
            {mode === 'login' && (intendedCourseTitle
              ? 'Sign in with your authorized credentials to access ' + intendedCourseTitle
              : 'Access your coursework, lecture modules, and evaluated projects.')}
            {mode === 'forgot' && 'Request an expiring password reset token for your account.'}
            {mode === 'reset' && 'Choose a strong, personal password for your institutional account.'}
          </p>
        </div>

        {/* Institutional Onboarding Notice */}
        <div className="bg-sky-50/70 border-b border-sky-100 px-4 py-2.5 flex items-start gap-2.5 text-[11px] text-sky-800">
          <ShieldAlert className="w-4 h-4 text-sky-600 shrink-0 mt-0.5" />
          <p className="leading-relaxed">
            <span className="font-bold">Institutional Access:</span> Public self-registration is disabled. All student and faculty accounts are provisioned exclusively by the platform administrator.
          </p>
        </div>

        {/* Form Body */}
        <div className="flex-1 min-h-0 flex flex-col overflow-hidden">
          {mode === 'login' && (
            <form onSubmit={handleLoginSubmit} className="flex flex-col flex-1 min-h-0 overflow-hidden">
              <div className="flex-1 min-h-0 overflow-y-auto p-4 sm:p-5 space-y-3.5 text-xs">
                {errorMsg && (
                  <div className="p-2.5 bg-rose-50 border border-rose-200 text-rose-700 rounded-xl text-xs font-semibold">
                    {errorMsg}
                  </div>
                )}
                {infoMsg && (
                  <div className="p-2.5 bg-emerald-50 border border-emerald-200 text-emerald-800 rounded-xl text-xs font-semibold flex items-center gap-2">
                    <CheckCircle2 className="w-4 h-4 text-emerald-600 shrink-0" />
                    <span>{infoMsg}</span>
                  </div>
                )}

                <div>
                  <label className="font-semibold text-slate-700 flex items-center gap-1.5 mb-1">
                    <Mail className="w-3.5 h-3.5 text-slate-400" />
                    Email Address
                  </label>
                  <input
                    type="email"
                    required
                    placeholder="Enter your registered institutional email"
                    value={loginEmail}
                    onChange={(e) => setLoginEmail(e.target.value)}
                    className="w-full px-3 py-2 bg-slate-50 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-[#0A7CB3] focus:bg-white text-xs text-slate-900"
                  />
                </div>

                <div>
                  <div className="flex items-center justify-between mb-1">
                    <label className="font-semibold text-slate-700 flex items-center gap-1.5">
                      <Lock className="w-3.5 h-3.5 text-slate-400" />
                      Password
                    </label>
                    <button
                      type="button"
                      onClick={() => {
                        setMode('forgot');
                        setErrorMsg('');
                        setInfoMsg('');
                        setForgotEmail(loginEmail);
                      }}
                      className="text-[11px] text-[#0A7CB3] hover:text-[#086491] font-semibold cursor-pointer"
                    >
                      Forgot password?
                    </button>
                  </div>
                  <div className="relative">
                    <input
                      type={showLoginPassword ? 'text' : 'password'}
                      required
                      placeholder="Enter your password"
                      value={loginPassword}
                      onChange={(e) => setLoginPassword(e.target.value)}
                      className="w-full px-3 py-2 pr-10 bg-slate-50 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-[#0A7CB3] focus:bg-white text-xs text-slate-900"
                    />
                    <button
                      type="button"
                      onClick={() => setShowLoginPassword(!showLoginPassword)}
                      className="absolute right-3 top-1/2 -translate-y-1/2 text-slate-400 hover:text-slate-700 transition-colors p-1"
                      aria-label={showLoginPassword ? 'Hide password' : 'Show password'}
                      tabIndex={-1}
                    >
                      {showLoginPassword ? <EyeOff className="w-4 h-4" /> : <Eye className="w-4 h-4" />}
                    </button>
                  </div>
                </div>

                {/* Sample Credentials Quick Autofill */}
                <div className="pt-2.5 border-t border-slate-100 flex flex-col sm:flex-row sm:items-center justify-between gap-1.5 text-[11px] text-slate-400">
                  <span className="font-medium shrink-0">Demo Access:</span>
                  <div className="flex flex-wrap items-center gap-1.5 sm:gap-2">
                    <button
                      type="button"
                      onClick={() => handleAutofill('admin@aaroha-inc.com', 'password123')}
                      className="text-[#0A7CB3] hover:text-[#086491] font-semibold underline cursor-pointer"
                    >
                      Admin
                    </button>
                    <span>•</span>
                    <button
                      type="button"
                      onClick={() => handleAutofill('faculty@aaroha-inc.com', 'password123')}
                      className="text-[#0A7CB3] hover:text-[#086491] font-semibold underline cursor-pointer"
                    >
                      Faculty
                    </button>
                    <span>•</span>
                    <button
                      type="button"
                      onClick={() => handleAutofill('student@aaroha-inc.com', 'password123')}
                      className="text-[#0A7CB3] hover:text-[#086491] font-semibold underline cursor-pointer"
                    >
                      Student
                    </button>
                    <span>•</span>
                    <button
                      type="button"
                      onClick={() => handleAutofill('coordinator@aaroha-inc.com', 'password123')}
                      className="text-[#0A7CB3] hover:text-[#086491] font-semibold underline cursor-pointer"
                    >
                      Coordinator
                    </button>
                    <span>•</span>
                    <button
                      type="button"
                      onClick={() => handleAutofill('placement@aaroha-inc.com', 'password123')}
                      className="text-[#0A7CB3] hover:text-[#086491] font-semibold underline cursor-pointer"
                    >
                      Placement
                    </button>
                  </div>
                </div>
              </div>

              {/* Pinned Action Button */}
              <div className="shrink-0 p-3.5 sm:p-4 bg-white border-t border-slate-100 shadow-[0_-4px_12px_rgba(0,0,0,0.03)]">
                <button
                  type="submit"
                  disabled={loading}
                  className="w-full py-2.5 sm:py-3 bg-[#0A7CB3] hover:bg-[#086491] disabled:opacity-50 text-white font-bold rounded-xl shadow-xs transition-colors flex items-center justify-center gap-2 cursor-pointer"
                >
                  {loading ? (
                    <span>Logging in...</span>
                  ) : (
                    <>
                      <span>Login</span>
                      <ArrowRight className="w-4 h-4" />
                    </>
                  )}
                </button>
              </div>
            </form>
          )}

          {mode === 'forgot' && (
            <form onSubmit={handleForgotSubmit} className="flex flex-col flex-1 min-h-0 overflow-hidden">
              <div className="flex-1 min-h-0 overflow-y-auto p-4 sm:p-5 space-y-3.5 text-xs">
                {errorMsg && (
                  <div className="p-2.5 bg-rose-50 border border-rose-200 text-rose-700 rounded-xl text-xs font-semibold">
                    {errorMsg}
                  </div>
                )}
                {infoMsg && (
                  <div className="p-2.5 bg-emerald-50 border border-emerald-200 text-emerald-800 rounded-xl text-xs font-semibold space-y-2">
                    <div className="flex items-center gap-2">
                      <CheckCircle2 className="w-4 h-4 text-emerald-600 shrink-0" />
                      <span>{infoMsg}</span>
                    </div>
                    {resetGeneratedLink && (
                      <div className="pt-2 border-t border-emerald-200/60 text-[11px] space-y-1">
                        <span className="text-emerald-900 font-bold block">Simulated Reset Link:</span>
                        <div className="p-1.5 bg-white border border-emerald-200 rounded text-slate-800 font-mono break-all select-all">
                          {resetGeneratedLink}
                        </div>
                        <p className="text-slate-500 text-[10px]">
                          Note: External SMTP is unconfigured in system settings. In production, this link is transmitted to the user inbox.
                        </p>
                        <div className="pt-1.5">
                          <button
                            type="button"
                            onClick={() => {
                              setMode('reset');
                              setErrorMsg('');
                              setInfoMsg('');
                            }}
                            className="px-3 py-1 bg-emerald-600 hover:bg-emerald-700 text-white font-semibold rounded-lg text-xs transition-colors cursor-pointer"
                          >
                            Proceed to Reset Password
                          </button>
                        </div>
                      </div>
                    )}
                  </div>
                )}

                <div>
                  <label className="font-semibold text-slate-700 flex items-center gap-1.5 mb-1">
                    <Mail className="w-3.5 h-3.5 text-slate-400" />
                    Registered Email Address *
                  </label>
                  <input
                    type="email"
                    required
                    placeholder="Enter your registered account email"
                    value={forgotEmail}
                    onChange={(e) => setForgotEmail(e.target.value)}
                    className="w-full px-3 py-2 bg-slate-50 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-[#0A7CB3] focus:bg-white text-xs text-slate-900"
                  />
                </div>
              </div>

              <div className="shrink-0 p-3.5 sm:p-4 bg-white border-t border-slate-100 flex items-center gap-3">
                <button
                  type="button"
                  onClick={() => {
                    setMode('login');
                    setErrorMsg('');
                    setInfoMsg('');
                  }}
                  className="px-3 py-2 bg-slate-100 hover:bg-slate-200 text-slate-700 font-semibold rounded-xl text-xs transition-colors flex items-center gap-1 cursor-pointer"
                >
                  <ArrowLeft className="w-3.5 h-3.5" />
                  <span>Back</span>
                </button>
                <button
                  type="submit"
                  disabled={loading}
                  className="flex-1 py-2.5 bg-[#0A7CB3] hover:bg-[#086491] disabled:opacity-50 text-white font-bold rounded-xl shadow-xs transition-colors flex items-center justify-center gap-2 cursor-pointer"
                >
                  {loading ? <span>Generating Token...</span> : <span>Generate Reset Token</span>}
                </button>
              </div>
            </form>
          )}

          {mode === 'reset' && (
            <form onSubmit={handleResetSubmit} className="flex flex-col flex-1 min-h-0 overflow-hidden">
              <div className="flex-1 min-h-0 overflow-y-auto p-4 sm:p-5 space-y-3.5 text-xs">
                {errorMsg && (
                  <div className="p-2.5 bg-rose-50 border border-rose-200 text-rose-700 rounded-xl text-xs font-semibold">
                    {errorMsg}
                  </div>
                )}

                <div>
                  <label className="font-semibold text-slate-700 flex items-center gap-1.5 mb-1">
                    <KeyRound className="w-3.5 h-3.5 text-slate-400" />
                    Reset Token *
                  </label>
                  <input
                    type="text"
                    required
                    placeholder="Paste your 48-character reset token"
                    value={resetToken}
                    onChange={(e) => setResetToken(e.target.value.trim())}
                    className="w-full px-3 py-2 bg-slate-50 border border-slate-200 rounded-xl font-mono focus:outline-none focus:ring-2 focus:ring-[#0A7CB3] focus:bg-white text-xs text-slate-900"
                  />
                </div>

                <div>
                  <label className="font-semibold text-slate-700 flex items-center gap-1.5 mb-1">
                    <Lock className="w-3.5 h-3.5 text-slate-400" />
                    New Password (Min 8 Characters) *
                  </label>
                  <input
                    type="password"
                    required
                    minLength={8}
                    placeholder="Enter your new password"
                    value={newPassword}
                    onChange={(e) => setNewPassword(e.target.value)}
                    className="w-full px-3 py-2 bg-slate-50 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-[#0A7CB3] focus:bg-white text-xs text-slate-900"
                  />
                </div>
              </div>

              <div className="shrink-0 p-3.5 sm:p-4 bg-white border-t border-slate-100 flex items-center gap-3">
                <button
                  type="button"
                  onClick={() => {
                    setMode('login');
                    setErrorMsg('');
                    setInfoMsg('');
                  }}
                  className="px-3 py-2 bg-slate-100 hover:bg-slate-200 text-slate-700 font-semibold rounded-xl text-xs transition-colors flex items-center gap-1 cursor-pointer"
                >
                  <ArrowLeft className="w-3.5 h-3.5" />
                  <span>Back</span>
                </button>
                <button
                  type="submit"
                  disabled={loading}
                  className="flex-1 py-2.5 bg-[#0A7CB3] hover:bg-[#086491] disabled:opacity-50 text-white font-bold rounded-xl shadow-xs transition-colors flex items-center justify-center gap-2 cursor-pointer"
                >
                  {loading ? <span>Updating Password...</span> : <span>Confirm New Password</span>}
                </button>
              </div>
            </form>
          )}
        </div>
      </div>
    </div>
  );
}
